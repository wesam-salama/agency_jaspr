// Reproducible browser verification against the owned local source preview.
const { chromium } = require('/Users/wesamsalama/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const fs = require('node:fs/promises');
const path = require('node:path');
const assert = require('node:assert/strict');
const BASE = process.env.FORM_PREVIEW_URL || 'http://127.0.0.1:8797/assets/selected-work/form/site/';
const ROOT = path.resolve(__dirname,'../verification');
const PROOFS = path.join(ROOT,'website');

(async()=>{
  await fs.mkdir(PROOFS,{recursive:true});
  const browser = await chromium.launch({executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true,args:['--no-sandbox']});
  const context = await browser.newContext({viewport:{width:1440,height:1050},deviceScaleFactor:1});
  const page = await context.newPage();
  page.on('dialog',dialog=>dialog.accept());
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  const evidence={date:'2026-10-13',scope:'Working local CMS; isolated browser context, no server publication',base:BASE,checks:[],screenshots:[]};
  const check=(name,detail)=>evidence.checks.push({name,result:'passed',detail});
  const capture=async(name)=>{await page.screenshot({path:path.join(PROOFS,name),fullPage:false});evidence.screenshots.push(`website/${name}`);};
  try{
    await page.goto(`${BASE}editor.html`,{waitUntil:'networkidle'});
    await page.locator('#field-title-en').waitFor();
    await page.locator('#field-title-en').fill('');
    await page.locator('#publish').click();
    await page.waitForFunction(()=>document.activeElement.id==='field-title-en');
    assert.equal(await page.locator('#field-title-en').getAttribute('aria-invalid'),'true');
    check('Required field blocks publishing and focuses first invalid input','The English title was cleared; publishing preserved the other input and focused the invalid title.');
    await capture('cms-validation-desktop.png');
    await page.locator('#field-title-en').fill('Courtyard House');
    const summary='One planted courtyard brings light, privacy, and daily movement into a compact home.';
    await page.locator('#field-summary-en').fill(summary);
    await page.locator('#publish').click();
    assert.match(await page.locator('#feedback').innerText(),/Preview your current/);
    check('Preview is required before publication','An unpreviewed changed draft did not reach the published local store.');
    await page.locator('#preview').click();
    const preview=page.frameLocator('#site-preview');
    await preview.locator('h1').filter({hasText:'Courtyard House'}).waitFor();
    await preview.getByText(summary,{exact:true}).first().waitFor();
    check('Actual implementation preview reads the edited draft','The public project template rendered the amended English summary from the separate session preview store.');
    await capture('cms-edit-desktop.png');
    await page.locator('#publish').click();
    await page.waitForFunction(()=>document.getElementById('feedback').textContent.includes('Published in this browser'),null,{timeout:20000});
    const published=await context.newPage();
    await published.goto(`${BASE}index.html?project=courtyard-house`,{waitUntil:'networkidle'});
    await published.getByText(summary,{exact:true}).first().waitFor();
    const publishedData=await page.evaluate(()=>JSON.parse(localStorage.getItem('form-projects-v1')));
    assert.equal(publishedData[0].summary.en,summary);
    check('Publish changes is read by the public website','A separate public page in this browser rendered the published summary. No external destination received data.');
    await published.screenshot({path:path.join(PROOFS,'cms-published-project.png'),fullPage:false});
    evidence.screenshots.push('website/cms-published-project.png');
    await published.setViewportSize({width:760,height:800});
    await published.locator('.project-title-row').screenshot({path:path.join(PROOFS,'cms-published-project-excerpt.png')});
    evidence.screenshots.push('website/cms-published-project-excerpt.png');
    await page.reload({waitUntil:'networkidle'});
    assert.equal(await page.locator('#field-summary-en').inputValue(),summary);
    check('Draft persists after reload','The changed summary and selected project were recovered from the separate draft store.');
    const oldMobile=await page.locator('#field-images-0-focal-mobile-x').inputValue();
    await page.locator('#field-images-0-focal-desktop-x').evaluate(input=>{input.value='36';input.dispatchEvent(new Event('input',{bubbles:true}));});
    assert.equal(await page.locator('#field-images-0-focal-mobile-x').inputValue(),oldMobile);
    assert.match(await page.locator('[data-crop="0-desktop"] img').getAttribute('style'),/36%/);
    const cropRules=await page.evaluate(()=>Object.fromEntries(['0-desktop','0-mobile','1-desktop','1-mobile','2-desktop','2-mobile','3-desktop','3-mobile'].map(key=>{
      const frame=document.querySelector(`[data-crop="${key}"]`);return [key,{ratio:getComputedStyle(frame).aspectRatio,fit:getComputedStyle(frame.querySelector('img')).objectFit}];
    })));
    assert.equal(cropRules['0-desktop'].ratio,'16 / 9');assert.equal(cropRules['0-mobile'].ratio,'4 / 3');
    for(const key of ['1-desktop','1-mobile','2-mobile'])assert.equal(cropRules[key].ratio,'4 / 3');
    assert.equal(cropRules['2-desktop'].ratio,'16 / 7');
    for(const key of ['3-desktop','3-mobile']){assert.equal(cropRules[key].ratio,'8 / 5');assert.equal(cropRules[key].fit,'contain');}
    check('Separate focal controls update the live project-page crop','Desktop horizontal focal point changed to 36%; the mobile point retained its original value. The opening image uses 16:9 desktop / 4:3 mobile, other story images 4:3, material details 16:7 desktop / 4:3 mobile, and diagrams show the full 8:5 drawing without cropping.');
    await page.locator('#field-images-0-focal-desktop-x').scrollIntoViewIfNeeded();
    await capture('cms-focal-desktop.png');
    const storyBefore=await page.locator('#field-sections-0-body-en').inputValue();
    await page.locator('[data-action="move-down"][data-index="0"]').focus();
    await page.locator('[data-action="move-down"][data-index="0"]').press('Enter');
    assert.equal(await page.locator('#field-sections-1-body-en').inputValue(),storyBefore);
    assert.equal(await page.locator('#field-sections-1-imageId').inputValue(),'exterior');
    assert.equal(await page.evaluate(()=>document.activeElement.dataset.index),'1',JSON.stringify(await page.evaluate(()=>({tag:document.activeElement.tagName,id:document.activeElement.id,html:document.activeElement.outerHTML.slice(0,300)}))));
    check('Keyboard-capable story reorder retains text and image relation','Moving the first story down kept its English/Arabic record and exterior image together and restored focus to the moved control.');
    await page.locator('[data-action="remove-image"][data-index="1"]').click();
    await page.locator('#publish').click();
    assert.equal(await page.locator('#field-sections-1-imageId').getAttribute('aria-invalid'),'true');
    assert.equal(await page.locator('#field-sections-1-body-en').inputValue(),storyBefore);
    check('Removed imagery blocks a missing relation without erasing story text','Removing the linked exterior image retained the moved chapter and its explanation; the missing chapter image was identified.');
    await page.locator('#discard').click();
    assert.equal(await page.locator('#field-images-0-focal-desktop-x').inputValue(),'50');
    await page.locator('#field-area').fill('');
    await page.locator('#field-title-en').fill('Courtyard House — a study of light, privacy, and planted space within a compact home');
    await page.setViewportSize({width:390,height:844});
    await page.locator('#editor-language').selectOption('ar');
    assert.equal(await page.locator('html').getAttribute('dir'),'rtl');
    assert.equal(await page.locator('#field-title-en').inputValue(),'Courtyard House — a study of light, privacy, and planted space within a compact home');
    await page.evaluate(()=>window.scrollTo(0,0));
    await capture('cms-arabic-mobile.png');
    const overflow=await page.evaluate(()=>document.documentElement.scrollWidth-innerWidth);
    assert.equal(overflow,0);
    check('Arabic editor preserves values and has no mobile overflow','At 390 px the interface switched to RTL, retained the long English draft title and absent optional area, and measured zero horizontal overflow.');
    await page.locator('#preview').click();
    await page.locator('#publish').click();
    await page.waitForFunction(()=>document.getElementById('feedback').textContent.includes('نُشرت النسخة في هذا المتصفح'),null,{timeout:20000});
    check('Long permitted title and absent optional area publish successfully','The bilingual draft was previewed and locally published with a long English title and an empty optional area.');
    await page.locator('#field-summary-en').fill('A preserved draft for the simulated browser-storage failure.');
    await page.locator('#preview').click();
    const preserved=await page.locator('#field-summary-en').inputValue();
    await page.evaluate(()=>{Storage.prototype.setItem=function(){throw new DOMException('Simulated blocked browser storage','SecurityError');};});
    await page.locator('#publish').click();
    await page.waitForFunction(()=>document.getElementById('feedback').textContent.includes('تعذّر حفظ النشر'),null,{timeout:20000});
    assert.equal(await page.locator('#field-summary-en').inputValue(),preserved);
    check('Storage failure preserves draft and offers retry','A controlled SecurityError left the typed draft intact and announced that browser storage must be enabled before retrying.');
    assert.deepEqual(errors,[]);
    evidence.consoleErrors=errors;
    evidence.status='passed';
  }catch(error){evidence.status='failed';evidence.failure=error.stack;await page.screenshot({path:path.join(PROOFS,'cms-failure.png'),fullPage:false});throw error;}
  finally{await fs.writeFile(path.join(ROOT,'cms-browser-checks.json'),JSON.stringify(evidence,null,2)+'\n');await browser.close();}
  console.log(JSON.stringify({status:evidence.status,checks:evidence.checks.length,screenshots:evidence.screenshots.length}));
})().catch(error=>{console.error(error.stack);process.exitCode=1;});
