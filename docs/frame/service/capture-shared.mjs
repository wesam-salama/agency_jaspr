import {createRequire} from 'node:module';
import {writeFile,readFile} from 'node:fs/promises';
import {resolve} from 'node:path';
import assert from 'node:assert/strict';
const require=createRequire(import.meta.url);
const {chromium}=require('/Users/wesamsalama/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const lang=process.env.FRAME_CAPTURE_LANG==='ar'?'ar':'en';const learner=lang==='ar'?'demo-ar':'demo';
const origin='http://127.0.0.1:8803';
const nativeProof=`docs/frame/verification/native/native-session-${lang}.json`;
const nativeRecord=JSON.parse(await readFile(nativeProof,'utf8'));
assert.equal(nativeRecord.xctestExit,0);assert.equal(nativeRecord.learner,learner);assert.equal(nativeRecord.language,lang);
const browser=await chromium.launch({headless:true,executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
async function recordScreen(path) {
 await page.locator('.shared-record').scrollIntoViewIfNeeded();
 const box=await page.locator('.shared-record').boundingBox();assert.ok(box);
 const dimensions=await page.evaluate(()=>({width:innerWidth,height:innerHeight}));
 const x=Math.max(0,box.x-20);const y=Math.max(0,box.y-16);
 await page.screenshot({path:resolve(path),clip:{x,y,width:Math.min(dimensions.width-x,box.width+40),height:Math.min(dimensions.height-y,box.height+32)}});
}
const apiRequests=[];const pageErrors=[];
page.on('request',request=>{if(new URL(request.url()).pathname.startsWith('/api/'))apiRequests.push({method:request.method(),path:new URL(request.url()).pathname});});
page.on('pageerror',error=>pageErrors.push(error.message));
const response=await page.request.get(origin+'/api/session?learner='+learner);const record=await response.json();
assert.ok(response.ok());assert.deepEqual(record,nativeRecord.after);
assert.equal(record.revision,3);assert.deepEqual(record.completed,['01']);assert.ok(record.drafts['01'].note.length>0);
await page.goto(origin+`/assets/selected-work/frame/site/?learner=${learner}&lang=${lang}#enrol`);
await page.locator('.practice-note').waitFor();await page.evaluate(()=>document.fonts.ready);
assert.equal(await page.locator('[role="progressbar"]').getAttribute('aria-valuenow'),'1');
assert.equal(await page.locator('.record-next h3 bdi').innerText(),'02');
assert.equal(await page.locator('.practice-note').innerText(),record.drafts['01'].note);
await page.screenshot({path:resolve(`docs/frame/verification/website/shared-progress-${lang}.png`),fullPage:true});
await recordScreen(`docs/frame/verification/website/saved-record-desktop-${lang}.png`);
await page.setViewportSize({width:390,height:1000});
await page.screenshot({path:resolve(`docs/frame/verification/website/shared-progress-mobile-${lang}.png`),fullPage:true});
await recordScreen(`docs/frame/verification/website/saved-record-mobile-${lang}.png`);
const afterResponse=await page.request.get(origin+'/api/session?learner='+learner);const afterRecord=await afterResponse.json();
assert.deepEqual(afterRecord,record);assert.deepEqual(pageErrors,[]);assert.ok(apiRequests.every(request=>request.method==='GET'));
await writeFile(`docs/frame/verification/website/shared-progress-${lang}.json`,JSON.stringify({date:'2026-10-14',capturedAtUTC:new Date().toISOString(),method:'Read-only website/API/native-record comparison after the actual native exercise and cold restart; state unchanged by capture',learner,course:'FA-PH-01',completed:record.completed,note:record.drafts['01'].note,attachment:record.drafts['01'].attachment,revision:record.revision,nextLesson:'02',nativeProof,nativeProofRawStartUTC:nativeRecord.rawStartUTC,apiRequests,pageErrors,screenshots:[`shared-progress-${lang}.png`,`shared-progress-mobile-${lang}.png`,`saved-record-desktop-${lang}.png`,`saved-record-mobile-${lang}.png`]},null,2)+'\n');
await browser.close();process.stdout.write(`${lang} shared website record matches the actual native saved exercise and1/6→02.\n`);
